// 自动回复无人问津的帖子
function autoReplyToUnanswered() {
  db.ensureBotUser();
  const posts = db.getUnansweredPosts(24); // 超过24小时没人回复
  let count = 0;
  posts.forEach(post => {
    const reply = generateReply(post);
    db.createReply(post.id, reply, '校园助手');
    count++;
  });
  if (count > 0) {
    console.log(`[Bot] 自动回复了 ${count} 条帖子`);
  }
  return count;
}

